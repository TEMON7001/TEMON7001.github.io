import { formatNumber as n } from "../core/plural.js";

export const meta = { id: "method", title: "Как считали", short: "Как считали", icon: "📖" };

export function mount(root, ctx) {
  const data = ctx.data;

  if (!data) {
    root.innerHTML =
      '<div class="card"><p class="result-warning">Справочник материалов не загрузился, ' +
      "показывать нечего. Переоткройте приложение.</p></div>";
    return;
  }

  root.innerHTML =
    '<p class="hint" style="margin:0 0 0.6rem">Все формулы и принятые запасы — здесь. ' +
    "Если норма расхода у вашего материала другая, поправьте её в параметрах на вкладке «Работы».</p>" +
    blocks(data).map(block).join("") +
    limits();
}

