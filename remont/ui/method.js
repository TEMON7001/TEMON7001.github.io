function block(item) {
  return (
    "<details class=\"card method\"" + (item.open ? " open" : "") + ">" +
    "<summary>" + item.title + "</summary>" +
    '<div class="method-body">' +
    '<ul class="formulas">' + item.formulas.map((f) => "<li>" + f + "</li>").join("") + "</ul>" +
    "<p>" + item.text + "</p>" +
    "</div></details>"
  );
}

